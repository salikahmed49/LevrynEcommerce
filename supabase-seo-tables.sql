-- 1. Product Reviews Table
CREATE TABLE IF NOT EXISTS product_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL,
  product_name TEXT,
  reviewer_name TEXT NOT NULL,
  rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
  title TEXT,
  review_text TEXT NOT NULL,
  approved BOOLEAN DEFAULT false,
  verified_purchase BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE product_reviews ENABLE ROW LEVEL SECURITY;

-- Allow anyone to read approved reviews
CREATE POLICY "Anyone can read approved reviews" ON product_reviews
  FOR SELECT USING (approved = true);

-- Allow anyone to insert reviews (they start as unapproved)
CREATE POLICY "Anyone can submit reviews" ON product_reviews
  FOR INSERT WITH CHECK (true);

-- 2. Page Views Table (for real-time analytics)
CREATE TABLE IF NOT EXISTS page_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_path TEXT NOT NULL,
  product_id INTEGER,
  session_id TEXT,
  user_agent TEXT,
  referrer TEXT,
  timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE page_views ENABLE ROW LEVEL SECURITY;

-- Allow anyone to insert page views
CREATE POLICY "Anyone can log page views" ON page_views
  FOR INSERT WITH CHECK (true);

-- Allow reading for analytics (admin use)
CREATE POLICY "Anyone can read page views" ON page_views
  FOR SELECT USING (true);

-- 3. Email Notification Queue (backup for EmailJS)
CREATE TABLE IF NOT EXISTS email_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email TEXT NOT NULL,
  subject TEXT NOT NULL,
  body JSONB NOT NULL,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  sent_at TIMESTAMPTZ
);

-- Enable RLS
ALTER TABLE email_notifications ENABLE ROW LEVEL SECURITY;

-- Allow inserts
CREATE POLICY "Anyone can queue emails" ON email_notifications
  FOR INSERT WITH CHECK (true);

-- 4. Create indexes for performance  
CREATE INDEX IF NOT EXISTS idx_page_views_timestamp ON page_views(timestamp);
CREATE INDEX IF NOT EXISTS idx_page_views_session ON page_views(session_id);
CREATE INDEX IF NOT EXISTS idx_page_views_path ON page_views(page_path);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON product_reviews(product_id);
CREATE INDEX IF NOT EXISTS idx_reviews_approved ON product_reviews(approved);

-- 5. Useful analytics views

-- Daily visitor count
CREATE OR REPLACE VIEW daily_visitors AS
SELECT 
  DATE(timestamp) as date,
  COUNT(DISTINCT session_id) as unique_visitors,
  COUNT(*) as total_page_views
FROM page_views
GROUP BY DATE(timestamp)
ORDER BY date DESC;

-- Popular pages
CREATE OR REPLACE VIEW popular_pages AS
SELECT 
  page_path,
  COUNT(*) as views,
  COUNT(DISTINCT session_id) as unique_views
FROM page_views
WHERE timestamp > NOW() - INTERVAL '30 days'
GROUP BY page_path
ORDER BY views DESC;
